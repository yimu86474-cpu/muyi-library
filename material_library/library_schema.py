def _upgrade_asset_schema(connection) -> None:
    asset_columns = {
        row["column_name"] for row in connection.execute("SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='assets'").fetchall()
    }
    source_columns = {
        row["column_name"] for row in connection.execute("SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='sources'").fetchall()
    }
    if "excluded_relative_prefixes_json" not in source_columns:
        connection.execute(
            "ALTER TABLE sources ADD COLUMN excluded_relative_prefixes_json TEXT NOT NULL DEFAULT '[]'"
        )
    scan_columns = {
        row["column_name"] for row in connection.execute("SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='scans'").fetchall()
    }
    for column, definition in {
        "batch_id": "TEXT",
        "proposed_missing": "INTEGER NOT NULL DEFAULT 0",
        "commit_status": "TEXT NOT NULL DEFAULT 'committed'",
        "enumeration_errors_json": "TEXT NOT NULL DEFAULT '[]'",
        "missing_candidate_token": "TEXT",
    }.items():
        if column not in scan_columns:
            connection.execute("ALTER TABLE scans ADD COLUMN {} {}".format(column, definition))
    migrations = {
        "display_name": "TEXT NOT NULL DEFAULT ''",
        "display_name_source": "TEXT NOT NULL DEFAULT 'filename_rule'",
        "display_name_status": "TEXT NOT NULL DEFAULT 'derived'",
        "content_hash": "TEXT",
        "content_hash_error": "TEXT",
        "trashed_at": "DOUBLE PRECISION",
        "lifecycle_stage": "TEXT NOT NULL DEFAULT 'needs_review'",
    }
    for column, definition in migrations.items():
        if column not in asset_columns:
            connection.execute(
                "ALTER TABLE assets ADD COLUMN {} {}".format(column, definition)
            )


def _upgrade_capture_schema(connection) -> bool:
    capture_columns = {
        row["column_name"] for row in connection.execute("SELECT column_name FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='captures'").fetchall()
    }
    media_refresh_status_added = "media_refresh_status" not in capture_columns
    capture_migrations = {
        "content_kind": "TEXT NOT NULL DEFAULT 'video'",
        "audio_url": "TEXT",
        "platform": "TEXT NOT NULL DEFAULT 'web'",
        "author_name": "TEXT NOT NULL DEFAULT ''",
        "thumbnail_url": "TEXT",
        "thumbnail_status": "TEXT NOT NULL DEFAULT 'unverified'",
        "thumbnail_error": "TEXT",
        "external_id": "TEXT NOT NULL DEFAULT ''",
        "like_count_text": "TEXT NOT NULL DEFAULT ''",
        "published_at_text": "TEXT NOT NULL DEFAULT ''",
        "note": "TEXT NOT NULL DEFAULT ''",
        "tags_json": "TEXT NOT NULL DEFAULT '[]'",
        "categories_json": "TEXT NOT NULL DEFAULT '[\"待分类\"]'",
        "favorite": "INTEGER NOT NULL DEFAULT 0",
        "seen_count": "INTEGER NOT NULL DEFAULT 1",
        "last_seen_at": "DOUBLE PRECISION NOT NULL DEFAULT 0",
        "media_obtained_at": "DOUBLE PRECISION",
        "media_last_verified_at": "DOUBLE PRECISION",
        "media_refresh_status": "TEXT NOT NULL DEFAULT 'ready'",
        "media_refresh_error": "TEXT",
    }
    for column, definition in capture_migrations.items():
        if column not in capture_columns:
            connection.execute(
                "ALTER TABLE captures ADD COLUMN {} {}".format(column, definition)
            )
    return media_refresh_status_added


def _repair_capture_preview_defaults(connection, media_refresh_status_added: bool) -> None:
    if media_refresh_status_added:
        connection.execute(
            """
            UPDATE captures
            SET media_refresh_status='needs_activation'
            WHERE platform='douyin'
              AND content_kind='video'
              AND NOT (status='downloaded' AND target_path IS NOT NULL)
              AND NOT (media_url LIKE 'http://%' OR media_url LIKE 'https://%')
              AND media_last_verified_at IS NULL
            """
        )
    # 早期预览迁移曾把所有未记录验证时间的抖音旧卡一律降级，
    # 即使卡片仍保留着可直接尝试的真实媒体地址。只恢复没有失败证据的
    # 这批旧卡；真正遇到 403/404/410 的卡会带 error，仍保持待激活。
    connection.execute(
        """
        UPDATE captures
        SET media_refresh_status='ready'
        WHERE platform='douyin'
          AND content_kind='video'
          AND NOT (status='downloaded' AND target_path IS NOT NULL)
          AND media_refresh_status='needs_activation'
          AND (media_url LIKE 'http://%' OR media_url LIKE 'https://%')
          AND media_last_verified_at IS NULL
          AND media_refresh_error IS NULL
        """
    )
    connection.execute(
        "UPDATE captures SET last_seen_at=updated_at WHERE last_seen_at=0"
    )
    connection.execute(
        "UPDATE captures SET thumbnail_status='verified_remote' "
        "WHERE thumbnail_url LIKE 'http%' AND (content_kind='image' OR platform<>'douyin') "
        "AND thumbnail_status='unverified'"
    )
    connection.execute(
        "UPDATE captures SET categories_json='[\"待分类\"]' "
        "WHERE categories_json IS NULL OR categories_json='' OR categories_json='[]'"
    )


def _restore_capture_categories(connection) -> None:
    now = _now()
    connection.execute(
        "INSERT INTO capture_categories(id, name, sort_order, created_at, updated_at) "
        "VALUES(%s, '待分类', 0, %s, %s) ON CONFLICT DO NOTHING",
        ("capture-category-pending", now, now),
    )
    imported_names = []
    for row in connection.execute(
        "SELECT categories_json FROM captures ORDER BY created_at"
    ).fetchall():
        try:
            values = json.loads(row["categories_json"] or "[]")
        except (TypeError, ValueError, json.JSONDecodeError):
            values = []
        for value in values if isinstance(values, list) else []:
            try:
                name = CaptureCategoryStore._normalize_capture_category_name(value)
            except ValueError:
                continue
            if name not in imported_names:
                imported_names.append(name)
    next_order = int(connection.execute(
        "SELECT COALESCE(MAX(sort_order), 0) AS value FROM capture_categories"
    ).fetchone()["value"])
    for name in imported_names:
        if name == "待分类":
            continue
        next_order += 1
        connection.execute(
            "INSERT INTO capture_categories(id, name, sort_order, created_at, updated_at) "
            "VALUES(%s, %s, %s, %s, %s) ON CONFLICT DO NOTHING",
            (uuid.uuid4().hex[:20], name, next_order, now, now),
        )


def _finalize_capture_indexes(connection) -> None:
    connection.execute(
        """
        UPDATE captures
        SET status='capture_pending',
            failure_reason='没有取得可预览的真实媒体地址（当前仅有 Blob 或空地址），只保留了作品页'
        WHERE content_kind='video'
            AND (media_url LIKE 'blob:%' OR media_url IS NULL OR media_url='')
            AND status='saved'
        """
    )
    connection.execute(
        "CREATE INDEX IF NOT EXISTS captures_page_url_idx ON captures(page_url)"
    )
    connection.execute(
        "CREATE INDEX IF NOT EXISTS captures_external_idx ON captures(platform, external_id)"
    )
    connection.execute(
        "CREATE INDEX IF NOT EXISTS captures_preview_refresh_idx "
        "ON captures(platform, media_refresh_status)"
    )


def _populate_asset_defaults(connection) -> None:
    unnamed = connection.execute(
        "SELECT id, relative_path, media_type FROM assets WHERE display_name=''"
    ).fetchall()
    for row in unnamed:
        connection.execute(
            "UPDATE assets SET display_name=%s, display_name_source='filename_rule', "
            "display_name_status='derived' WHERE id=%s",
            (readable_display_name(row["relative_path"], row["media_type"]), row["id"]),
        )
    for index, name in enumerate(DEFAULT_CATEGORIES):
        connection.execute(
            "INSERT INTO categories(name, sort_order) VALUES(%s, %s) ON CONFLICT DO NOTHING",
            (name, index),
        )


def initialize_library(connection, lock) -> None:
    """保留一个外层事务，幂等升级按原顺序进行。"""
    with lock, connection.transaction():
        connection.execute(SCHEMA)
        _upgrade_asset_schema(connection)
        media_refresh_status_added = _upgrade_capture_schema(connection)
        _repair_capture_preview_defaults(connection, media_refresh_status_added)
        _restore_capture_categories(connection)
        _finalize_capture_indexes(connection)
        _populate_asset_defaults(connection)
